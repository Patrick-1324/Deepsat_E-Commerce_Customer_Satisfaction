# Human-readable derived feature preview
# -----------------------------------------------------------------------------
def _fmt_number(value, decimals=1):
    if value is None:
        return "Not available"

    try:
        if pd.isna(value):
            return "Not available"
    except Exception:
        pass

    value = float(value)

    if abs(value - round(value)) < 1e-9:
        return f"{int(round(value)):,}"

    return f"{value:,.{decimals}f}"


def build_derived_preview(feature_frame):
    row = feature_frame.iloc[0]

    return {
        "response_time_minutes": (
            _fmt_number(row.get("response_time_minutes"))
        ),
        "order_to_issue_hours": (
            _fmt_number(row.get("order_to_issue_hours"))
        ),
        "survey_delay_hours": (
            _fmt_number(row.get("survey_delay_hours"))
        ),
        "issue_day_name": (
            "Not available"
            if pd.isna(row.get("issue_day_name"))
            else str(row.get("issue_day_name"))
        ),
        "issue_hour_bucket": (
            "Not available"
            if pd.isna(row.get("issue_hour_bucket"))
            else str(row.get("issue_hour_bucket"))
        ),
        "remarks_word_count": (
            _fmt_number(row.get("remarks_word_count"))
        ),
    }


# -----------------------------------------------------------------------------
# Prediction
# -----------------------------------------------------------------------------
def predict_csat(raw_frame):
    feature_frame = build_features(raw_frame)
    derived_preview = build_derived_preview(feature_frame)

    for feature in MODEL_FEATURES:
        if feature not in feature_frame.columns:
            feature_frame[feature] = np.nan

    model_input = feature_frame[MODEL_FEATURES]
    processed = preprocessor.transform(model_input).astype(np.float32)

    raw_probs = model.predict(processed, verbose=0)[0].astype(float)

    divisor = np.asarray(
        decision_config.get(
            "probability_divisor",
            np.ones_like(raw_probs, dtype=float).tolist(),
        ),
        dtype=float,
    )

    if divisor.shape != raw_probs.shape:
        raise ValueError(
            "decision_config probability_divisor does not match "
            "the ANN output."
        )

    safe_divisor = np.where(divisor <= 0, 1.0, divisor)
    adjusted_probs = raw_probs / safe_divisor

    total = adjusted_probs.sum()
    if total > 0:
        adjusted_probs /= total

    predicted_index = int(np.argmax(adjusted_probs))
    predicted_score = int(
        label_encoder.inverse_transform([predicted_index])[0]
    )

    probabilities = [
        {
            "score": int(score),
            "probability": float(adjusted_probs[i]),
        }
        for i, score in enumerate(label_encoder.classes_)
    ]

    return {
        "predicted_score": predicted_score,
        "model_probability": float(adjusted_probs[predicted_index]),
        "probabilities": probabilities,
        "model_name": MODEL_NAME,
        "derived": derived_preview,
    }


