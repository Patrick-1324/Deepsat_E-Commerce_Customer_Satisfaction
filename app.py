@app.route("/", methods=["GET", "POST"])
def index():
    result = None
    error = None
    submitted = {}

    if request.method == "POST":
        submitted = request.form.to_dict()

        try:
            raw_frame = form_to_raw_frame(request.form)
            result = predict_csat(raw_frame)
        except Exception as exc:
            error = str(exc)

    return render_template(
        "index.html",
        result=result,
        error=error,
        submitted=submitted,
        training_options=TRAINING_OPTIONS,
        constraints=UI_CONSTRAINTS,
        model_name=MODEL_NAME,
        metrics=deployment_metrics,
        constraint_source=UI_CONSTRAINTS.get(
            "source_dataset",
            "training dataset",
        ),
    )


