def _clean_category_value(value):
    if value is None:
        return None
    try:
        if pd.isna(value):
            return None
    except Exception:
        pass
    return str(value)


def extract_training_options():
    options = {}

    cat_pipeline = preprocessor.named_transformers_["cat"]
    onehot = cat_pipeline.named_steps["onehot"]

    for index, feature in enumerate(CATEGORICAL_FEATURES):
        values = [
            _clean_category_value(v)
            for v in onehot.categories_[index]
        ]
        values = [
            v for v in values
            if v is not None and v.strip() != ""
        ]
        options[feature] = sorted(set(values), key=str.casefold)

    return options


TRAINING_OPTIONS = extract_training_options()

# Root choices are tightened using source-dataset relationships.
TRAINING_OPTIONS["category"] = sorted(
    UI_CONSTRAINTS["category_to_subcategories"].keys(),
    key=str.casefold,
)
TRAINING_OPTIONS["manager"] = sorted(
    UI_CONSTRAINTS["manager_to_supervisors"].keys(),
    key=str.casefold,
)


