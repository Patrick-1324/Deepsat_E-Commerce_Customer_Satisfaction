def blank_to_nan(value):
    if value is None:
        return np.nan
    if isinstance(value, str) and value.strip() == "":
        return np.nan
    return value


def has_value(value):
    if value is None:
        return False
    try:
        if pd.isna(value):
            return False
    except Exception:
        pass
    return str(value).strip() != ""


def compound_key(*values):
    return SEP.join(str(v) for v in values)


def validate_remarks(value):
    """
    Optional remarks may be blank.
    If supplied, require at least one letter or digit so punctuation-only
    values such as '.', '-', '...' are not treated as meaningful remarks.
    """
    if not has_value(value):
        return

    text = str(value).strip()
    if not re.search(r"[A-Za-z0-9]", text):
        raise ValueError(
            "Customer remarks contains only punctuation/symbols. "
            "Leave it blank or enter a meaningful remark."
        )


def validate_training_combinations(row):
    errors = []

    category = row.get("category")
    sub_category = row.get("sub_category")

    if has_value(category) and has_value(sub_category):
        valid_subs = UI_CONSTRAINTS[
            "category_to_subcategories"
        ].get(str(category), [])

        if str(sub_category) not in valid_subs:
            errors.append(
                f"Sub-category '{sub_category}' was not observed under "
                f"Category '{category}' in the training data."
            )

    manager = row.get("manager")
    supervisor = row.get("supervisor")
    agent = row.get("agent_name")
    tenure = row.get("tenure_bucket")
    shift = row.get("agent_shift")

    if has_value(manager) and has_value(supervisor):
        valid_supervisors = UI_CONSTRAINTS[
            "manager_to_supervisors"
        ].get(str(manager), [])

        if str(supervisor) not in valid_supervisors:
            errors.append(
                f"Supervisor '{supervisor}' was not observed under "
                f"Manager '{manager}'."
            )

    if has_value(manager) and has_value(supervisor) and has_value(agent):
        key = compound_key(manager, supervisor)

        valid_agents = UI_CONSTRAINTS[
            "manager_supervisor_to_agents"
        ].get(key, [])

        if str(agent) not in valid_agents:
            errors.append(
                f"Agent '{agent}' was not observed under the selected "
                "Manager/Supervisor combination."
            )

    if (
        has_value(manager)
        and has_value(supervisor)
        and has_value(agent)
        and has_value(tenure)
    ):
        key = compound_key(manager, supervisor, agent)

        valid_tenure = UI_CONSTRAINTS[
            "manager_supervisor_agent_to_tenure"
        ].get(key, [])

        if str(tenure) not in valid_tenure:
            errors.append(
                f"Tenure bucket '{tenure}' was not observed for the "
                "selected agent hierarchy."
            )

    if (
        has_value(manager)
        and has_value(supervisor)
        and has_value(agent)
        and has_value(shift)
    ):
        key = compound_key(manager, supervisor, agent)

        valid_shift = UI_CONSTRAINTS[
            "manager_supervisor_agent_to_shift"
        ].get(key, [])

        if str(shift) not in valid_shift:
            errors.append(
                f"Agent shift '{shift}' was not observed for the selected "
                "agent hierarchy."
            )

    if errors:
        raise ValueError(" ".join(errors))


def form_to_raw_frame(form):
    row = {
        field: blank_to_nan(form.get(field))
        for field in RAW_INPUT_FIELDS
    }

    validate_remarks(row.get("customer_remarks"))
    validate_training_combinations(row)

    parsed = {}
    for field in [
        "order_date_time",
        "issue_reported_at",
        "issue_responded",
        "survey_response_date",
    ]:
        value = row[field]
        parsed[field] = (
            pd.NaT
            if not has_value(value)
            else pd.to_datetime(value, errors="coerce")
        )

    if (
        pd.notna(parsed["issue_reported_at"])
        and pd.notna(parsed["issue_responded"])
        and parsed["issue_responded"] < parsed["issue_reported_at"]
    ):
        raise ValueError(
            "Issue responded time cannot be earlier than issue reported time."
        )

    if (
        pd.notna(parsed["order_date_time"])
        and pd.notna(parsed["issue_reported_at"])
        and parsed["issue_reported_at"] < parsed["order_date_time"]
    ):
        raise ValueError(
            "Issue reported time cannot be earlier than order time."
        )

    if (
        pd.notna(parsed["issue_responded"])
        and pd.notna(parsed["survey_response_date"])
        and parsed["survey_response_date"] < parsed["issue_responded"]
    ):
        raise ValueError(
            "Survey response time cannot be earlier than issue responded time."
        )

    return pd.DataFrame([row], columns=RAW_INPUT_FIELDS)


